import { chromium } from 'playwright-core';
import fs from 'node:fs';
const b=['C:\Program Files\Google\Chrome\Application\chrome.exe','C:\Program Files (x86)\Microsoft\Edge\Application\msedge.exe'].find(p=>fs.existsSync(p));
const br=await chromium.launch({executablePath:b,headless:true,args:['--mute-audio']});
const p=await br.newPage(); const bad=[];
p.on('response',r=>{ if(r.status()>=400) bad.push(r.status()+' '+r.url()); });
await p.goto('https://hollowcraft.vercel.app/index.html',{waitUntil:'load',timeout:60000});
await new Promise(r=>setTimeout(r,6000));
console.log('__hc:', await p.evaluate(()=>typeof window.__hc));
console.log('btn frame:', await p.evaluate(()=>getComputedStyle(document.querySelector('#mb-solo')).borderImageSource.slice(0,120)));
console.log('failed requests:', bad.slice(0,8));
await br.close();
